def prepare_collector(c,raw,identity,case):
    from tools.learning.admitted_collection import FormalEpisodeBuffer
    raw=deepcopy(raw);raw['case']=case;raw['episode_id']=identity
    c._folder=c.output/identity;c._folder.mkdir()
    c._record=dict(episode_id=identity,case=case,seed=2026092716,qualification_sha256=c.admission.expected_digest,
                   steps=len(raw['transitions']),status='collecting')
    c.attempts.append(c._record)
    c._fault_info=None;c.active=True
    c._start_counts=deepcopy(c.updater.counts);c._start_fingerprints=c.updater.fingerprints()
    c._policy_sha=c._start_fingerprints['actor'];c._start_count=deepcopy(c.updater.counts)
    c.audit_archive_wall_s=0.;c.sampling_mode='uniform_warmup'
    c.buffer=FormalEpisodeBuffer()
    # Inject already-recorded rows at the protocol boundary only. No claim that
    # these test-case actions were newly generated by this fresh test network.
    c.buffer._pending=raw['transitions'];c.buffer._boundary=True
    env=SimpleNamespace(guard_facts=raw['guard_facts'],events=raw['events'],stop_samples=raw['stop_samples'],
        phase='STOPPING',data=SimpleNamespace(time=raw['audit_end_time_s']),config=SimpleNamespace(timestep=.0002))
    c.session=SimpleNamespace(env=env,done=True,reason=raw['final_session']['reason'],
        task_finished=raw['final_session']['task_finished'],stop_time=raw['stop_time'])
    return raw


def collect_fixture(chain,raw=None):
    raw=fixture() if raw is None else raw
    case=chain.sampler.next_case();c=chain.collector
    raw=prepare_collector(c,raw,case['name'],case)
    chain.warmup.rng.bit_generator.advance(4*len(raw['transitions']))
    def archive_only(policy,steps):
        c._seal()
        return dict(steps=len(raw['transitions']),episode_finished=True)
    c.collect=archive_only
    return chain.collect(1)


