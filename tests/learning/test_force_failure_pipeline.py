def test_review_frequency_stop_finishes_run_ledger_without_runtime_fault(tmp_path,monkeypatch):
    from tools.learning import bounded_cycle as cycle
    from tools.learning.bounded_contact import RunLedger
    chain=chain_at(tmp_path/'episodes');ledger=RunLedger(tmp_path/'ledger.json')
    # Synthetic completed initial stage; no evaluation calls.
    for i in range(4):ledger.start('initial',str(i));ledger.finish(dict(synthetic_only=True))
    starts=[];checkpoints=[]
    def protocol_start(identity):
        starts.append(identity);case=chain.sampler.next_case()
        raw=prepare_collector(chain.collector,fixture(),identity,case)
        chain.warmup.rng.bit_generator.advance(4*len(raw['transitions']))
        def archive_only(policy,steps):
            chain.collector._seal();return dict(episode_finished=True)
        chain.collector.collect=archive_only
    def no_update(*args):raise AssertionError('No update allowed at frequency threshold')
    def checkpoint_stub(chain,path):
        checkpoints.append(str(path));return 'SYNTHETIC-CHECKPOINT-STUB'
    monkeypatch.setattr(chain,'start',protocol_start)
    monkeypatch.setattr(chain,'update',no_update)
    monkeypatch.setattr(cycle.cp,'save_checkpoint',checkpoint_stub)
    with pytest.raises(RuntimeError,match='two_consecutive'):
        cycle.train(chain,ledger=ledger,output=tmp_path/'training')
    saved=json.loads(ledger.path.read_text(encoding='utf-8'))
    assert saved['active'] is None and saved['attempts'][-1]['status']=='finished'
    assert saved['attempts'][-1]['result']['success'] is False
    assert saved['status']=='stopped' and saved['stop_kind']=='force_failure_frequency'
    assert saved['stop_reason']=='two_consecutive_force_failures' and 'error' not in saved
    assert starts==['train_00','train_01'] and len(checkpoints)==1
    assert chain.updater.counts['critic']==0 and len(chain.replay)==12586
    assert (tmp_path/'training/controlled_stop.json').is_file()
    assert not (tmp_path/'training/failure.json').exists()
    assert not (chain.collector.output/'failure.json').exists()
    with pytest.raises(RuntimeError):cycle.cp.capture(chain)
    with pytest.raises(RuntimeError):ledger.start('training','train_02')


def test_controlled_stop_propagates_through_outer_runner(tmp_path,monkeypatch):
    from tools.learning import bounded_cycle as cycle
    from tools.learning.bounded_contact import ForceFailureStop
    monkeypatch.setattr(cycle,'DELIVERY',tmp_path)
    def no_fault(exc):raise AssertionError('Controlled stop must not call the runtime fault handler')
    monkeypatch.setattr(cycle,'BoundedCollection',lambda **kwargs:SimpleNamespace(fail=no_fault))
    monkeypatch.setattr(cycle.cp,'save_checkpoint',lambda *a:'SYNTHETIC-CHECKPOINT-STUB')
    monkeypatch.setattr(cycle,'evaluate',lambda *a,**kw:None)
    def stopped_train(chain,*,ledger,output):
        exc=ForceFailureStop('two_consecutive_force_failures','train_01')
        ledger.start('training','train_01');ledger.finish(dict(success=False,task_outcome='CONTACT_GUARD'))
        ledger.stop(exc);raise exc
    monkeypatch.setattr(cycle,'train',stopped_train)
    with pytest.raises(ForceFailureStop):cycle.execute(permit())
    run=tmp_path/'run';saved=json.loads((run/'ledger.json').read_text(encoding='utf-8'))
    assert saved['status']=='stopped' and saved['active'] is None and 'error' not in saved
    assert not (run/'failure.json').exists() and not (run/'frozen.json').exists()
    assert json.loads((run/'controlled_stop.json').read_text(encoding='utf-8'))['kind']=='force_failure_frequency'
